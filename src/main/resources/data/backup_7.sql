-- =====================================================================
-- Métricas de documentos generados por plantilla Word completa (tópico
-- Kafka judicial-documentos-generado-v2, publicado por ms-jurisia-judicial).
--   CabDocumentoPlantillaGenerado  (una fila por generación, exitosa o fallida)
--   DetDocumentoPlantillaVariable  (cómo se resolvió cada variable del Word)
-- Las tablas del flujo por secciones (CabDocumentoGenerado) no se modifican.
-- =====================================================================

CREATE TABLE If Not Exists JURISDB_METRICS.CabDocumentoPlantillaGenerado (
  id bigint unsigned primary key not null auto_increment,
  sessionUID char(50) NOT NULL Comment 'UUID de la generación (trazable con JURISDB_CONSULTATIONIA.GeminiDocumentoPlantilla)',
  typedoc char(20) DEFAULT NULL Comment 'doc o web',
  status tinyint DEFAULT NULL Comment '1 exitoso, 2 error',
  mensajeError varchar(1000) DEFAULT NULL Comment 'Detalle del error de la generación',
  userId bigint DEFAULT NULL Comment 'ID de Usuario',
  username varchar(100) DEFAULT NULL Comment 'Username del usuario',
  nombreUsuario varchar(250) DEFAULT NULL Comment 'Nombres y apellidos del usuario',
  cargo varchar(200) DEFAULT NULL Comment 'Cargo del usuario',
  idDependencia bigint DEFAULT NULL Comment 'ID de dependencia del usuario',
  dependencia varchar(250) DEFAULT NULL Comment 'Dependencia del usuario',
  nUnico bigint DEFAULT NULL Comment 'ID de expediente en el SIJ',
  numIncidente char(20) DEFAULT NULL Comment 'Número de incidente',
  codSede char(20) DEFAULT NULL,
  sede char(200) DEFAULT NULL,
  codInstancia char(20) DEFAULT NULL,
  instancia char(200) DEFAULT NULL,
  codEspecialidad char(20) DEFAULT NULL,
  especialidad char(200) DEFAULT NULL,
  codMateria char(20) DEFAULT NULL,
  materia char(200) DEFAULT NULL,
  codNumero char(20) DEFAULT NULL,
  codYear char(20) DEFAULT NULL,
  xFormato varchar(100) DEFAULT NULL Comment 'Número de expediente con formato',
  ubicacion varchar(200) DEFAULT NULL,
  juez varchar(200) DEFAULT NULL,
  especialista varchar(200) DEFAULT NULL,
  estado varchar(100) DEFAULT NULL,
  dniDemandante varchar(500) DEFAULT NULL,
  demandante text,
  dniDemandado varchar(500) DEFAULT NULL,
  demandado text,
  cantidadDemandantes int DEFAULT NULL,
  cantidadDemandados int DEFAULT NULL,
  idTipoDocumento bigint DEFAULT NULL,
  tipoDocumento varchar(150) DEFAULT NULL,
  idDocumento bigint DEFAULT NULL,
  documento varchar(200) DEFAULT NULL,
  idPlantilla bigint DEFAULT NULL,
  codigoPlantilla varchar(50) DEFAULT NULL,
  nombreOutPlantilla varchar(150) DEFAULT NULL,
  versionPlantilla int DEFAULT NULL,
  corregirIA tinyint DEFAULT NULL Comment 'Configuración de la plantilla al generar',
  tamanioPlantillaBytes bigint DEFAULT NULL,
  tamanioSalidaBytes bigint DEFAULT NULL Comment 'Bytes del .docx o del HTML generado',
  totalVariables int DEFAULT NULL,
  variablesSij int DEFAULT NULL,
  variablesCalculadas int DEFAULT NULL,
  variablesManuales int DEFAULT NULL,
  variablesIA int DEFAULT NULL,
  variablesNoDefinidas int DEFAULT NULL,
  variablesSinValor int DEFAULT NULL Comment 'Variables que quedaron como ...',
  reemplazosRealizados int DEFAULT NULL,
  estadoIA char(20) DEFAULT NULL Comment 'NO_APLICA, EXITOSO o ERROR',
  mensajeIA varchar(1000) DEFAULT NULL,
  parrafosEnviadosIA int DEFAULT NULL,
  parrafosCorregidosIA int DEFAULT NULL,
  bloquesSolicitadosIA int DEFAULT NULL,
  bloquesGeneradosIA int DEFAULT NULL,
  model char(50) DEFAULT NULL,
  roleSystem text,
  temperature decimal(3,1) DEFAULT NULL,
  configurationsId int DEFAULT NULL,
  finishReason varchar(50) DEFAULT NULL,
  promptTokens int DEFAULT NULL,
  candidatesTokens int DEFAULT NULL,
  thoughtsTokens int DEFAULT NULL,
  cachedTokens int DEFAULT NULL,
  totalTokens int DEFAULT NULL,
  tiempoSijMs bigint DEFAULT NULL,
  tiempoIAMs bigint DEFAULT NULL,
  tiempoTotalMs bigint DEFAULT NULL,
  regDate date Null Comment 'Fecha create',
  regDatetime datetime Null Comment 'Fecha Hora create',
  regTimestamp bigint Null Comment 'Epoch create'
)
ENGINE = INNODB,
CHARACTER SET utf8mb4,
COLLATE utf8mb4_general_ci,
COMMENT = 'Documentos generados por plantilla Word completa (métricas)';
-- Indexacion
ALTER TABLE JURISDB_METRICS.CabDocumentoPlantillaGenerado
    ADD UNIQUE INDEX cdpg_sessionUIDUNQ (sessionUID),
    ADD INDEX cdpg_userIdIDX (userId),
    ADD INDEX cdpg_typedocIDX (typedoc),
    ADD INDEX cdpg_statusIDX (status),
    ADD INDEX cdpg_estadoIAIDX (estadoIA),
    ADD INDEX cdpg_codSedeIDX (codSede),
    ADD INDEX cdpg_codInstanciaIDX (codInstancia),
    ADD INDEX cdpg_codEspecialidadIDX (codEspecialidad),
    ADD INDEX cdpg_nUnicoIDX (nUnico),
    ADD INDEX cdpg_idTipoDocumentoIDX (idTipoDocumento),
    ADD INDEX cdpg_idDocumentoIDX (idDocumento),
    ADD INDEX cdpg_idPlantillaIDX (idPlantilla),
    ADD INDEX cdpg_codigoPlantillaIDX (codigoPlantilla),
    ADD INDEX cdpg_modelIDX (model),
    ADD INDEX cdpg_regDateIDX (regDate),
    ADD INDEX cdpg_regTimestampIDX (regTimestamp);


CREATE TABLE If Not Exists JURISDB_METRICS.DetDocumentoPlantillaVariable (
  id bigint unsigned primary key not null auto_increment,
  idCab bigint unsigned DEFAULT NULL Comment 'ID de CabDocumentoPlantillaGenerado',
  sessionUID char(50) DEFAULT NULL Comment 'UUID de la generación',
  userId bigint DEFAULT NULL Comment 'ID de Usuario',
  idPlantilla bigint DEFAULT NULL,
  codigoPlantilla varchar(50) DEFAULT NULL,
  nombre varchar(100) DEFAULT NULL Comment 'Nombre de la variable en el Word',
  tipo char(20) DEFAULT NULL Comment 'SIJ, CALCULADA, MANUAL, IA o NO_DEFINIDA',
  campoSistema varchar(100) DEFAULT NULL Comment 'Clave del catálogo de sistema usada',
  tieneValor tinyint DEFAULT NULL Comment '1 con valor, 0 quedó como ...',
  regDate date Null Comment 'Fecha create',
  regDatetime datetime Null Comment 'Fecha Hora create',
  regTimestamp bigint Null Comment 'Epoch create'
)
ENGINE = INNODB,
CHARACTER SET utf8mb4,
COLLATE utf8mb4_general_ci,
COMMENT = 'Variables resueltas por documento generado por plantilla (métricas)';
-- Indexacion
ALTER TABLE JURISDB_METRICS.DetDocumentoPlantillaVariable
    ADD INDEX ddpv_idCabIDX (idCab),
    ADD INDEX ddpv_sessionUIDIDX (sessionUID),
    ADD INDEX ddpv_idPlantillaIDX (idPlantilla),
    ADD INDEX ddpv_nombreIDX (nombre),
    ADD INDEX ddpv_tipoIDX (tipo),
    ADD INDEX ddpv_tieneValorIDX (tieneValor),
    ADD INDEX ddpv_regDateIDX (regDate);
